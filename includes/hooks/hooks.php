/**
 * Ensure BuddyPress directory pages are real pages.
 *
 * Gated behind `wptsall_hooks_auto_corrections` option (ISS-HOK-015).
 *
 * @return void
 */
function wptsall_ensure_bp_directory_pages() {
	$bp_pages = get_option( 'bp-pages', array() );
	if ( empty( $bp_pages ) || ! is_array( $bp_pages ) ) {
		return;
	}
	foreach ( $bp_pages as $pid ) {
		$pid = intval( $pid );
		if ( ! $pid ) {
			continue;
		}
		$p = get_post( $pid );
		if ( $p && 'page' !== $p->post_type ) {
			wp_update_post(
				array(
					'ID'          => $pid,
					'post_type'   => 'page',
					'post_status' => 'publish',
				)
			);
			wptsall_log_info(
				'hooks',
				'Auto-corrected BP directory page type',
				array( 'post_id' => $pid, 'old_type' => $p->post_type )
			);
		}
	}
}

