// ISS-HOK-015: BuddyPress directory-page auto-corrections gated behind option (default off).
// Enable via: update_option( 'wptsall_hooks_auto_corrections', true );
// Note: Do NOT register an unprefixed `buddypress` CPT — WordPress.org requires
// CPT identifiers to use a plugin prefix, and it would conflict with real BuddyPress.
